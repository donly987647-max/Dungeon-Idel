 for(const enemy of c.enemies){
  for(const item of kit.items.filter(d=>d.rarity==='일반'))site.loot.push({id:item.id,source:'kill',enemy:enemy.name,chance:rules.normalChance,min:1,max:1});
  for(const [i,item] of kit.materials.entries())site.loot.push({id:item.id,source:'kill',enemy:enemy.name,chance:i?rules.epicMaterialChance:rules.rareMaterialChance,min:1,max:1});
 }
 for(const item of kit.items.filter(d=>d.rarity==='전설'))site.loot.push({id:item.id,source:'kill',enemy:c.boss.name,chance:rules.legendaryChance,min:1,max:1,pool:'legendary'});
