import {readFileSync,readdirSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {roster} from '../content/roster-v015.mjs';
const root=fileURLToPath(new URL('../',import.meta.url));
const files=['campaign-support.sql','roster-support.sql','economy-support.sql','game_process_expedition_action.sql'];
const target=readdirSync(root+'supabase/migrations').filter(x=>x.endsWith('_v015_campaign_runtime.sql'));
if(target.length!==1)throw new Error('Create the v015_campaign_runtime migration with the Supabase CLI first.');
const templates=JSON.stringify(Object.fromEntries(roster.map(r=>[r.family,r]))).replaceAll("'","''");
const templateSql=`create or replace function public.game_species_template(p_family text) returns jsonb language sql immutable set search_path=public as $$select '${templates}'::jsonb->p_family$$;\nrevoke all on function public.game_species_template(text) from public,anon,authenticated;\ngrant execute on function public.game_species_template(text) to service_role;\n`;
const sql='-- Generated by node tools/build-campaign-runtime.mjs\n'+templateSql+files.map(file=>`\n-- ${file}\n`+readFileSync(root+'supabase/gameplay/'+file,'utf8')).join('\n');
writeFileSync(root+'supabase/migrations/'+target[0],sql);
console.log(target[0]);
